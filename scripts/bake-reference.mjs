import {readFile,writeFile} from 'node:fs/promises';
import {PNG} from 'pngjs';
const png=PNG.sync.read(await readFile('public/references/wassie-canonical.png'));
const at=(x,y)=>{const i=(y*png.width+x)*4;return [...png.data.subarray(i,i+4)];};
// Canonical reference regions are authored once, in source-image pixels. The
// white exterior is flood-filled; enclosed white eyes, chest and feet survive.
const regions={head:[100,480,820,1050],torso:[28,1040,665,1884],leftFoot:[160,1858,362,2044],rightFoot:[335,1858,650,2015]};
const profiles={};
for(const [name,[left,top,right,bottom]]of Object.entries(regions)){
 const width=96,height=Math.round((bottom-top)/(right-left)*width),bytes=new Uint8Array(width*height*4);
 for(let y=0;y<height;y++)for(let x=0;x<width;x++){const p=at(Math.min(png.width-1,Math.floor(left+(x+.5)/width*(right-left))),Math.min(png.height-1,Math.floor(top+(y+.5)/height*(bottom-top))));bytes.set(p,(y*width+x)*4);}
 const exterior=new Uint8Array(width*height),queue=[];
 const white=i=>bytes[i*4]>230&&bytes[i*4+1]>230&&bytes[i*4+2]>230;
 const enqueue=(x,y)=>{if(x<0||x>=width||y<0||y>=height)return;const i=y*width+x;if(exterior[i]||!white(i))return;exterior[i]=1;queue.push(i);};
 for(let x=0;x<width;x++){enqueue(x,0);enqueue(x,height-1);}for(let y=0;y<height;y++){enqueue(0,y);enqueue(width-1,y);}
 for(let j=0;j<queue.length;j++){const i=queue[j],x=i%width,y=Math.floor(i/width);enqueue(x-1,y);enqueue(x+1,y);enqueue(x,y-1);enqueue(x,y+1);}
 for(let i=0;i<exterior.length;i++)if(exterior[i])bytes[i*4+3]=0;
 profiles[name]={width,height,pixels:Buffer.from(bytes).toString('base64'),crop:[left,top,right,bottom]};
}
await writeFile('src/assets/canonical-data.ts',`// Generated by scripts/bake-reference.mjs from the supplied canonical reference.\nexport const canonicalData = ${JSON.stringify(profiles)};\n`);
console.log('Baked four canonical silhouette/color profiles; retained the original PNG.');
